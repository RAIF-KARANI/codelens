def test_deleting_edge_target_keeps_edge_for_relinking(empty_database_url: str) -> None:
    command.upgrade(alembic_config(empty_database_url), "head")

    [edge] = run_sql(
        empty_database_url,
        "INSERT INTO repos (full_name) VALUES ('acme/app')",
        "INSERT INTO files (repo_id, path, language, content_hash)"
        " VALUES (1, 'a.py', 'python', 'h')",
        "INSERT INTO code_nodes (repo_id, file_id, kind, name, qualified_name, start_line,"
        " end_line, code, content_hash) VALUES"
        " (1, 1, 'function', 'caller', 'a.caller', 1, 2, '', 'h'),"
        " (1, 1, 'function', 'callee', 'a.callee', 3, 4, '', 'h')",
        "INSERT INTO code_edges (repo_id, src_node_id, dst_node_id, kind, target_name)"
        " VALUES (1, 1, 2, 'calls', 'a.callee')",
        "DELETE FROM code_nodes WHERE id = 2",
        "SELECT dst_node_id, target_name FROM code_edges",
    )

    assert edge.dst_node_id is None
    assert edge.target_name == "a.callee"


