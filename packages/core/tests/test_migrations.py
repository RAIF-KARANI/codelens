import asyncio
from typing import Any

import pytest
from alembic import command
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine

from core.config import get_settings
from core.db.migrate import alembic_config

pytestmark = pytest.mark.integration

SCHEMA_TABLES = {
    "repos",
    "files",
    "code_nodes",
    "code_edges",
    "anti_patterns",
    "reviews",
    "findings",
    "index_runs",
}


def run_sql(database_url: str, *statements: str) -> list[Any]:
    """Run statements in one transaction; return the rows of the last one."""

    async def _run() -> list[Any]:
        engine = create_async_engine(database_url)
        try:
            async with engine.begin() as conn:
                result = None
                for statement in statements:
                    result = await conn.execute(text(statement))
                return list(result) if result is not None and result.returns_rows else []
        finally:
            await engine.dispose()

    return asyncio.run(_run())


def public_tables(database_url: str) -> set[str]:
    rows = run_sql(database_url, "SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
    return {row.tablename for row in rows}


def test_upgrade_creates_full_schema(empty_database_url: str) -> None:
    command.upgrade(alembic_config(empty_database_url), "head")

    assert public_tables(empty_database_url) == SCHEMA_TABLES | {"alembic_version"}

    extensions = run_sql(empty_database_url, "SELECT extname FROM pg_extension")
    assert "vector" in {row.extname for row in extensions}

    indexes = {
        row.indexname: row.indexdef
        for row in run_sql(
            empty_database_url,
            "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = 'public'",
        )
    }
    assert "USING hnsw (embedding vector_cosine_ops)" in indexes["ix_code_nodes_embedding_hnsw"]
    assert "USING hnsw (embedding vector_cosine_ops)" in indexes["ix_anti_patterns_embedding_hnsw"]
    assert "USING gin (tsv)" in indexes["ix_code_nodes_tsv"]
    assert "(repo_id, qualified_name)" in indexes["ix_code_nodes_repo_id_qualified_name"]
    assert "WHERE (dst_node_id IS NULL)" in indexes["ix_code_edges_unresolved"]
    assert {"ix_code_edges_src_node_id", "ix_code_edges_dst_node_id"} <= indexes.keys()
    # Node identity for re-indexing; its index also replaces the old file_id index.
    assert (
        "UNIQUE INDEX uq_code_nodes_file_id_qualified_name_ordinal"
        in (indexes["uq_code_nodes_file_id_qualified_name_ordinal"])
    )
    assert "ix_code_nodes_file_id" not in indexes

    [embedding_type] = run_sql(
        empty_database_url,
        "SELECT format_type(atttypid, atttypmod) AS type FROM pg_attribute "
        "WHERE attrelid = 'code_nodes'::regclass AND attname = 'embedding'",
    )
    assert embedding_type.type == f"vector({get_settings().embed_dim})"


def test_downgrade_removes_everything(empty_database_url: str) -> None:
    config = alembic_config(empty_database_url)
    command.upgrade(config, "head")

    command.downgrade(config, "base")

    assert public_tables(empty_database_url) == {"alembic_version"}
    extensions = run_sql(empty_database_url, "SELECT extname FROM pg_extension")
    assert "vector" not in {row.extname for row in extensions}


